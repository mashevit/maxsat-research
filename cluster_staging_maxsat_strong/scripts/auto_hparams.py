#!/usr/bin/env python3
"""Instance-aware v3 hyperparameters: the batch config, and a preview of what jobs choose.

The choice itself happens at run time, inside each job: a config with
`hparams: auto` makes src/cli/run_memetic_shard.py call
src/evo/auto_hparams.resolve() after its kernel gate and merge the values in
memory. No per-instance config is written. This script (workstation only; the
login node runs no Python) does two things:

  1. writes the ONE batch config, configs/strong/auto.yaml (BASE + hparams: auto):
       python3 scripts/auto_hparams.py --write-base [--flips-c 0 --flips-cap 1600000]
       python3 scripts/auto_hparams.py --check          # the file equals the generator

  2. previews, with the same resolve() a job runs, what each instance gets:
       python3 scripts/auto_hparams.py --instance data/x.wcnf
       python3 scripts/auto_hparams.py --list instances.txt [--map preview.csv]

`--list` takes one path per line (or a TSV/CSV whose first column is the path;
lines starting with # are skipped). Paths are relative to the tree root.
`--config` previews another base config instead of configs/strong/auto.yaml.
"""
from __future__ import annotations

import argparse
import collections
import csv
import io
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from evo.auto_hparams import FLIPS_CAP_DEFAULT, RULESET, auto_base, hparams_opts, preview  # noqa: E402
from sat.cnf import WCNF  # noqa: E402

BASE_PATH = "configs/strong/auto.yaml"


def base_text(flips_c: float, flips_cap: int) -> str:
    head = (f"# {RULESET}: the batch config for instance-aware v3 runs.\n"
            "# Generated by scripts/auto_hparams.py --write-base -- do not edit by hand.\n"
            "# Each job chooses ea.mutation_k, ls.dls_*, ls.ls_polish_flips/flip_budget\n"
            "# (and polish_cap when flips_c > 0) at run time from the instance it solves,\n"
            "# plus ea.pop_size 10 and hard.moves.keep_sat ks2 when it has hard clauses\n"
            "# (and hard.moves.per_polish 10 when its v3 neighbour tables are lean);\n"
            "# rules and evidence: src/evo/auto_hparams.py. Record field: `hparams`.\n")
    return head + yaml.safe_dump(auto_base(flips_c, flips_cap), sort_keys=False)


def read_list(path: str):
    out = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line and not line.startswith("#"):
                out.append(line.replace(",", "\t").split("\t")[0].strip())
    return out


def preview_rows(cfg, instances):
    rows = []
    for inst in instances:
        r = preview(cfg, WCNF.parse_dimacs(os.path.join(ROOT, inst)))
        f = r.feats
        rows.append({"instance": inst, "class": f.cls, "gate": f.gate, "n_vars": f.n_vars,
                     "n_clauses": f.n_clauses, "n_hard": f.n_hard, "n_eff": f.n_eff, "m_eff": f.m_eff,
                     "n_hard_eff": f.n_hard_eff, "weighted": f.weighted, "soft_w_max": f.soft_w_max,
                     "mutation_k": r.overrides["ea"]["mutation_k"], "dls_t": r.overrides["ls"]["dls_t"],
                     "dls_sp": r.overrides["ls"]["dls_sp"], "dls_zeta": r.overrides["ls"]["dls_zeta"],
                     "dls_h_inc": r.overrides["ls"]["dls_h_inc"],
                     "ls_polish_flips": r.overrides["ls"]["ls_polish_flips"],
                     "pop_size": r.cfg["ea"]["pop_size"],
                     "keep_sat": ((r.cfg.get("hard") or {}).get("moves") or {}).get("keep_sat", "none"),
                     "resolved_config_hash": r.cfg_hash, "hparams_s": round(r.seconds, 4)})
    return rows


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--write-base", action="store_true", help=f"write {BASE_PATH}")
    p.add_argument("--check", action="store_true", help=f"compare {BASE_PATH} with the generator")
    p.add_argument("--flips-c", type=float, default=0.0, help="R3 flips per effective variable (0 = 12,500 always)")
    p.add_argument("--flips-cap", type=int, default=FLIPS_CAP_DEFAULT, help="R3 upper cap on flips per call")
    p.add_argument("--instance", action="append", default=[], help="instance to preview (repeatable)")
    p.add_argument("--list", help="file with one instance path per line, to preview")
    p.add_argument("--config", help=f"base config to preview with (default {BASE_PATH})")
    p.add_argument("--map", help="write the preview as CSV (relative to the tree root)")
    a = p.parse_args(argv)

    base_file = os.path.join(ROOT, BASE_PATH)
    if a.write_base:
        os.makedirs(os.path.dirname(base_file), exist_ok=True)
        with open(base_file, "w", encoding="utf-8") as fh:
            fh.write(base_text(a.flips_c, a.flips_cap))
        print(f"wrote {BASE_PATH}")
    if a.check:
        ok = os.path.exists(base_file) and open(base_file, encoding="utf-8").read() == base_text(a.flips_c, a.flips_cap)
        print(f"check: {BASE_PATH} {'identical' if ok else 'DIFFERS'}")
        if not ok:
            return 1

    instances = list(a.instance) + (read_list(a.list) if a.list else [])
    if not instances:
        if not (a.write_base or a.check):
            p.error("give --write-base, --check, --instance or --list")
        return 0
    cfg_path = os.path.join(ROOT, a.config) if a.config else base_file
    if os.path.exists(cfg_path):
        with open(cfg_path, encoding="utf-8") as fh:
            cfg = yaml.safe_load(fh) or {}
    elif a.config:
        p.error(f"no such config: {a.config}")
    else:
        cfg = auto_base(a.flips_c, a.flips_cap)
    if hparams_opts(cfg) is None:
        p.error("the base config has no `hparams: auto`")
    rows = preview_rows(cfg, instances)
    if a.map:
        buf = io.StringIO()
        w = csv.DictWriter(buf, fieldnames=list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
        with open(os.path.join(ROOT, a.map), "w", encoding="utf-8") as fh:
            fh.write(buf.getvalue())
    if len(rows) <= 20:
        for r in rows:
            print(f"{r['instance']}: class {r['class']}, n {r['n_vars']} -> n_eff {r['n_eff']} "
                  f"(gate {r['gate']}); k {r['mutation_k']}, dls t {r['dls_t']} sp {r['dls_sp']} "
                  f"zeta {r['dls_zeta']} h_inc {r['dls_h_inc']}, flips {r['ls_polish_flips']}, "
                  f"pop {r['pop_size']}, keep_sat {r['keep_sat']}")
    cls = collections.Counter(r["class"] for r in rows)
    print(f"{len(rows)} instances; classes {dict(cls)}; "
          f"{len({r['resolved_config_hash'] for r in rows})} distinct resolved configs"
          + (f"; preview written to {a.map}" if a.map else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
