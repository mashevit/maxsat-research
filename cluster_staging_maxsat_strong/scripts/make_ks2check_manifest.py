#!/usr/bin/env python3
"""Batch KS2: keep-satisfied feasible moves against today's move, on every MSE instance
with hard clauses and a proven optimum.

docs/current2/KS2_CHECK_RUN.md (repo). Workstation only (the login node runs no
Python). Writes, from the tree root:

  configs/strong/ks2check_<arm>.yaml          one config per arm
  scripts/instances_ks2check.csv              the instances (also copies them into data/)
  scripts/manifest_ks2check.tsv / .tasks.csv / .sha256 / .upload.sha256
  scripts/rsync_files_ks2check.txt

    python3 scripts/make_ks2check_manifest.py            # write
    python3 scripts/make_ks2check_manifest.py --check    # regenerate in memory, compare

Instances: the EvalMaxSAT s1 rows (MSE 2023/2024, 3600 s cap) that are `optimal`
and verified and have hard clauses -- 16, every one equal to its year's
best-known. The two soft-only drmx-cryptogen instances are left out (no moves).

Arms, 2 x 2 (N-2026-10-21-d): move {today's M, ks2} x pop {40, 10}; everything
else is configs/strong/auto.yaml (B1-B5, kernel gate, hparams: auto).
16 instances x 4 arms x seeds 1-3 = 192 tasks, 900 s, stop at the oracle.
"""
from __future__ import annotations

import argparse
import copy
import csv
import io
import json
import os
import shutil
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

import make_oracle900_manifest as o9  # noqa: E402  (sha256, family, upload helpers)
from evo.auto_hparams import auto_base  # noqa: E402

STEM = "manifest_ks2check"
STAGE = "ks2check"
INSTANCES_CSV = "scripts/instances_ks2check.csv"
SEEDS = (1, 2, 3)
BUDGET = 900
ARMS = {  # name: (pop_size, keep_sat)
    "m40": (40, "none"),
    "m10": (10, "none"),
    "ks2_40": (40, "ks2"),
    "ks2_10": (10, "ks2"),
}
INST_COLS = ["pop_idx", "instance", "instance_sha256", "year", "family", "oracle_cost", "evalmaxsat_s",
             "n_hard"]
SIDECAR = ["task_id", "job_id", "stage", "arm", "config_id", "config", "pop_size", "keep_sat",
           "ls_time_limit_s", "deadline_mode", "solver_seed", "budget_s", "pop_idx", "instance",
           "instance_sha256", "year", "family", "oracle_cost", "evalmaxsat_s", "memetic_impl",
           "ls_polish_flips", "ls_polish_cap", "preprocess", "ls_native"]


def config_path(arm: str) -> str:
    return f"configs/strong/ks2check_{arm}.yaml"


def config_text(arm: str) -> str:
    pop, keep = ARMS[arm]
    cfg = copy.deepcopy(auto_base())
    cfg["ea"]["pop_size"] = pop
    if keep != "none":
        cfg["hard"] = {"moves": {"keep_sat": keep}}
    head = (f"# Batch KS2, arm `{arm}`: pop {pop}, hard.moves.keep_sat {keep}.\n"
            "# Generated by scripts/make_ks2check_manifest.py -- do not edit by hand.\n"
            "# Base: configs/strong/auto.yaml (auto_hparams.auto_base); docs/current2/KS2_CHECK_RUN.md (repo).\n")
    return head + yaml.safe_dump(cfg, sort_keys=False)


def select(staging: str):
    rows = []
    for line in open(os.path.join(staging, "results", "evalmaxsat_mse_s1_all.jsonl"), encoding="utf-8"):
        r = json.loads(line)
        row = r["row"]
        if row["status"] == "optimal" and row.get("verified") and int(row["n_hard"]) > 0:
            if r["best_known"] is not None and int(r["best_known"]) != int(row["opt_cost"]):
                raise SystemExit(f"FATAL: optimum {row['opt_cost']} != best-known {r['best_known']}: {r['instance']}")
            rows.append({"instance": r["instance"], "year": r["year"], "oracle_cost": int(row["opt_cost"]),
                         "evalmaxsat_s": round(float(row["time_s"]), 3), "n_hard": int(row["n_hard"])})
    rows.sort(key=lambda x: (x["year"], x["instance"]))
    for i, x in enumerate(rows, 1):
        x["pop_idx"] = f"k{i:02d}"
        x["family"] = o9.family(x["instance"])
        x["instance_sha256"] = o9.sha256(os.path.join(staging, x["instance"]))
    return rows


def ensure_instances(staging: str):
    rows = select(staging)
    for r in rows:
        src, dst = os.path.join(staging, r["instance"]), os.path.join(ROOT, r["instance"])
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        if not os.path.isfile(dst) or o9.sha256(dst) != r["instance_sha256"]:
            shutil.copy2(src, dst)
        if o9.sha256(dst) != r["instance_sha256"]:
            raise SystemExit(f"FATAL: copy of {r['instance']} does not match")
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=INST_COLS, lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    return rows, buf.getvalue()


def build(rows, inst_csv: str):
    files = {config_path(a): config_text(a) for a in ARMS}
    files[INSTANCES_CSV] = inst_csv
    out, lines = [], []
    for arm, (pop, keep) in ARMS.items():
        for inst in rows:
            for seed in SEEDS:
                job = f"k2_{arm}_{inst['pop_idx']}_s{seed}"
                cid = f"ks2check_{arm}"
                out.append({
                    "task_id": len(out) + 1, "job_id": job, "stage": STAGE, "arm": arm, "config_id": cid,
                    "config": config_path(arm), "pop_size": pop, "keep_sat": keep, "ls_time_limit_s": 3.5,
                    "deadline_mode": "clip", "solver_seed": seed, "budget_s": BUDGET, "pop_idx": inst["pop_idx"],
                    "instance": inst["instance"], "instance_sha256": inst["instance_sha256"], "year": inst["year"],
                    "family": inst["family"], "oracle_cost": inst["oracle_cost"],
                    "evalmaxsat_s": inst["evalmaxsat_s"], "memetic_impl": "v3", "ls_polish_flips": 12500,
                    "ls_polish_cap": "flips", "preprocess": "kernel", "ls_native": "1",
                })
                lines.append("\t".join([job, inst["instance"], config_path(arm), cid, str(seed), str(BUDGET),
                                        str(inst["oracle_cost"]), "evalmaxsat", "evalmaxsat_mse_s1"]) + "\n")
    files[f"scripts/{STEM}.tsv"] = "".join(lines)
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=SIDECAR, lineterminator="\n")
    w.writeheader()
    w.writerows(out)
    files[f"scripts/{STEM}.tasks.csv"] = buf.getvalue()
    files[f"scripts/{STEM}.sha256"] = "".join(f"{i['instance_sha256']}  {i['instance']}\n" for i in rows)
    return files


def upload_paths(rows):
    src, _, scripts, _ = o9.upload_paths([])
    scripts = [p for p in scripts if "oracle900" not in p] + [
        "scripts/make_oracle900_manifest.py", "scripts/make_ks2check_manifest.py", INSTANCES_CSV,
        f"scripts/{STEM}.tsv", f"scripts/{STEM}.tasks.csv", f"scripts/{STEM}.sha256"]
    return src, [config_path(a) for a in ARMS], scripts, [r["instance"] for r in rows]


def rsync_text(groups, n_tasks):
    src, cfgs, scripts, data = groups
    out = [f"# rsync --files-from list for batch KS2 ({n_tasks} tasks; docs/current2/KS2_CHECK_RUN.md, repo).",
           "# Paths relative to cluster_staging_maxsat_strong/. Destination: ~/cluster_staging_maxsat_strong/.",
           f"# After the rsync: sha256sum -c scripts/{STEM}.upload.sha256 on the login node.",
           "#", "# 1. code (src/, including the C core source; build it once with scripts/build_native.sbatch)"]
    out += src + ["# 2. configs (one per arm)"] + cfgs
    out += ["# 3. driver, submit, build, results, manifest"] + scripts
    out += [f"scripts/{STEM}.upload.sha256", f"scripts/rsync_files_{STAGE}.txt"]
    out += [f"# 4. instances ({len(data)})"] + data
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--staging", default=o9.STAGING)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    rows, inst_csv = ensure_instances(a.staging) if not a.check else (None, None)
    if a.check:
        rows = list(csv.DictReader(open(os.path.join(ROOT, INSTANCES_CSV), encoding="utf-8")))
        inst_csv = open(os.path.join(ROOT, INSTANCES_CSV), encoding="utf-8").read()
        files = build(rows, inst_csv)
        bad = [p for p, txt in files.items()
               if not os.path.isfile(os.path.join(ROOT, p)) or open(os.path.join(ROOT, p), encoding="utf-8").read() != txt]
        if bad:
            print("DIFFERS:", *bad, sep="\n  ")
            return 1
        print(f"OK: {len(files)} files reproduce byte for byte")
        return 0
    files = build(rows, inst_csv)
    for p, txt in files.items():
        full = os.path.join(ROOT, p)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8", newline="") as f:
            f.write(txt)
    n = files[f"scripts/{STEM}.tsv"].count("\n")
    groups = upload_paths(rows)
    rsync = f"scripts/rsync_files_{STAGE}.txt"
    with open(os.path.join(ROOT, rsync), "w", encoding="utf-8") as f:
        f.write(rsync_text(groups, n))
    every = [p for g in groups for p in g] + [rsync]
    with open(os.path.join(ROOT, "scripts", f"{STEM}.upload.sha256"), "w", encoding="utf-8") as f:
        f.writelines(f"{o9.sha256(os.path.join(ROOT, p))}  {p}\n" for p in every)
    print(f"wrote {len(files)} files + upload list; {len(rows)} instances; {n} tasks; {len(every)} upload hashes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
