#!/usr/bin/env python3
"""Batch POP: the population size R4 sets on instances with hard clauses, {10, 40}, on
every MSE 2023/2024 instance with hard clauses that we hold (HMSE 141 + rail 3).

docs/current2/POPSIZE_RUN.md (repo). Workstation only (the login node runs no
Python). Writes, from the tree root:

  configs/strong/popsize_<arm>.yaml           one config per arm
  scripts/instances_popsize.csv               the instances
  scripts/manifest_popsize.tsv / .tasks.csv / .sha256 / .upload.sha256
  scripts/rsync_files_popsize.txt

    python3 scripts/make_popsize_manifest.py            # write
    python3 scripts/make_popsize_manifest.py --check    # regenerate in memory, compare

User, 2026-10-25: "do prepare run for some data we already have, not mse26, I want
to check if with pop10 instead pop40 is better, prepare rule, that takes into
account fitness, and arrival at optimum".

Instances: scripts/instances_hardmse.csv (h001-h141, its targets) and the 3 setcover
rail files with their MSE 2024 best-knowns (as in batch PP10; they run on lean
tables, so R5 sets per_polish 10 in both arms). Both arms are auto_hparams/3; they
differ only in `hparams.hard_pop`, the pop R4 chooses (10 = today's default).
Every instance has hard clauses, so R4 applies in every task.
144 instances x 2 arms x seeds 1-3 = 864 tasks, 900 s, stop at the target.
"""
from __future__ import annotations

import argparse
import copy
import csv
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

import make_hardmse_manifest as hm  # noqa: E402  (family, the HMSE instances)
import make_oracle900_manifest as o9  # noqa: E402  (sha256, upload helpers)
import make_perpolish_manifest as pp  # noqa: E402  (rail files, MSE 2024 best-knowns)
import make_under30_manifest as u3  # noqa: E402  (sidecar_csv, write_upload, check_or_write)
from evo.auto_hparams import auto_base  # noqa: E402

STEM = "manifest_popsize"
STAGE = "popsize"
INSTANCES_CSV = "scripts/instances_popsize.csv"
SEEDS = (1, 2, 3)
BUDGET = 900
ARMS = {"pop10": 10, "pop40": 40}           # name: hparams.hard_pop
INST_COLS = ["pop_idx", "group", "src_idx", "instance", "instance_sha256", "year", "family", "oracle_cost",
             "oracle_kind", "weighted"]
# pop_size is the config's value (40); R4 sets hard_pop at run time (the record's `hparams` field).
SIDECAR = ["task_id", "job_id", "stage", "arm", "config_id", "config", "hard_pop", "pop_size", "ls_time_limit_s",
           "deadline_mode", "solver_seed", "budget_s", "pop_idx", "group", "src_idx", "instance", "instance_sha256",
           "year", "family", "oracle_cost", "oracle_kind", "weighted", "memetic_impl", "ls_polish_flips",
           "ls_polish_cap", "preprocess", "ls_native"]


def config_path(arm: str) -> str:
    return f"configs/strong/popsize_{arm}.yaml"


def config_text(arm: str) -> str:
    cfg = copy.deepcopy(auto_base())
    cfg["hparams"] = {"mode": "auto", "hard_pop": ARMS[arm]}
    head = (f"# Batch POP, arm `{arm}`: R4 sets ea.pop_size {ARMS[arm]} on instances with hard clauses.\n"
            "# Generated by scripts/make_popsize_manifest.py -- do not edit by hand.\n"
            "# Base: configs/strong/auto.yaml (auto_hparams.auto_base, rule set /3); only hparams.hard_pop\n"
            "# differs between the arms. docs/current2/POPSIZE_RUN.md (repo).\n")
    return head + yaml.safe_dump(cfg, sort_keys=False)


def select(staging: str):
    """HMSE 141, then rail 3; the instance files must already be in this tree."""
    rows = []
    with open(os.path.join(ROOT, hm.INSTANCES_CSV), encoding="utf-8") as f:
        for r in csv.DictReader(f):
            rows.append({"group": "hmse", "src_idx": r["pop_idx"], "instance": r["instance"],
                         "instance_sha256": r["instance_sha256"], "year": r["year"],
                         "oracle_cost": int(r["oracle_cost"]), "oracle_kind": r["oracle_kind"],
                         "weighted": r["weighted"]})
    best = pp.bestknown_mse24(staging)
    for fname in pp.RAIL:
        inst = f"{pp.RAIL_DIR}/{fname}"
        rows.append({"group": "rail", "src_idx": fname.split("-")[-1].split(".")[0], "instance": inst,
                     "instance_sha256": o9.sha256(os.path.join(ROOT, inst)), "year": "mse24",
                     "oracle_cost": best[fname], "oracle_kind": "best_known", "weighted": "1"})
    seen = set()
    for i, r in enumerate(rows, 1):
        if r["instance"] in seen:
            raise SystemExit(f"FATAL: {r['instance']} selected twice")
        seen.add(r["instance"])
        if o9.sha256(os.path.join(ROOT, r["instance"])) != r["instance_sha256"]:
            raise SystemExit(f"FATAL: {r['instance']} does not match its recorded sha256")
        r["pop_idx"] = f"p{i:03d}"
        r["family"] = hm.family(os.path.basename(r["instance"]))
    return rows


def build(insts):
    files = {config_path(a): config_text(a) for a in ARMS}
    files[INSTANCES_CSV] = u3.sidecar_csv(INST_COLS, insts)
    out, lines = [], []
    for arm, hp in ARMS.items():
        cid = f"popsize_{arm}"
        for inst in insts:
            tier, run = ("evalmaxsat", "evalmaxsat_mse_s1") if inst["oracle_kind"] == "proven" else (
                "bestknown", f"bestknown_{inst['year']}")
            for seed in SEEDS:
                job = f"po_{arm}_{inst['pop_idx']}_s{seed}"
                out.append({
                    "task_id": len(out) + 1, "job_id": job, "stage": STAGE, "arm": arm, "config_id": cid,
                    "config": config_path(arm), "hard_pop": hp, "pop_size": 40, "ls_time_limit_s": 3.5,
                    "deadline_mode": "clip", "solver_seed": seed, "budget_s": BUDGET,
                    "pop_idx": inst["pop_idx"], "group": inst["group"], "src_idx": inst["src_idx"],
                    "instance": inst["instance"], "instance_sha256": inst["instance_sha256"],
                    "year": inst["year"], "family": inst["family"], "oracle_cost": inst["oracle_cost"],
                    "oracle_kind": inst["oracle_kind"], "weighted": inst["weighted"], "memetic_impl": "v3",
                    "ls_polish_flips": 12500, "ls_polish_cap": "flips", "preprocess": "kernel", "ls_native": "1",
                })
                lines.append("\t".join([job, inst["instance"], config_path(arm), cid, str(seed), str(BUDGET),
                                        str(inst["oracle_cost"]), tier, run]) + "\n")
    files[f"scripts/{STEM}.tsv"] = "".join(lines)
    files[f"scripts/{STEM}.tasks.csv"] = u3.sidecar_csv(SIDECAR, out)
    files[f"scripts/{STEM}.sha256"] = "".join(f"{i['instance_sha256']}  {i['instance']}\n" for i in insts)
    return files


def upload_paths(insts):
    src, _, scripts, _ = o9.upload_paths([])
    scripts = [p for p in scripts if "oracle900" not in p] + [
        "scripts/make_oracle900_manifest.py", "scripts/make_under30_manifest.py", "scripts/make_hardmse_manifest.py",
        "scripts/make_perpolish_manifest.py", "scripts/make_popsize_manifest.py", "scripts/make_flat_upload.py",
        INSTANCES_CSV, f"scripts/{STEM}.tsv", f"scripts/{STEM}.tasks.csv", f"scripts/{STEM}.sha256"]
    return src, [config_path(a) for a in ARMS], scripts, [i["instance"] for i in insts]


def file_list_text(groups, n_tasks):
    src, cfgs, scripts, data = groups
    out = [f"# File list for batch POP ({n_tasks} tasks; docs/current2/POPSIZE_RUN.md, repo).",
           "# Paths relative to cluster_staging_maxsat_strong/. Destination: ~/cluster_staging_maxsat_strong/.",
           f"# After the upload: sha256sum -c scripts/{STEM}.upload.sha256 on the login node.",
           "#", "# 1. code (src/; ls_core.c unchanged since the PP10 rebuild, the .so stays)"]
    out += src + ["# 2. configs (one per arm)"] + cfgs
    out += ["# 3. driver, submit, build, results, manifest"] + scripts
    out += [f"scripts/{STEM}.upload.sha256", f"scripts/rsync_files_{STAGE}.txt"]
    out += [f"# 4. instances ({len(data)})"] + data
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--staging", default=o9.STAGING, help="tree holding bestknown_mse24.csv")
    ap.add_argument("--check", action="store_true", help="regenerate the manifest files in memory and compare")
    a = ap.parse_args(argv)
    insts = select(a.staging)
    files = build(insts)
    if a.check:
        return u3.check_or_write(files, True)
    u3.check_or_write(files, False)
    n = files[f"scripts/{STEM}.tsv"].count("\n")
    groups = upload_paths(insts)
    k = u3.write_upload(STEM, STAGE, groups, file_list_text(groups, n))
    print(f"wrote {len(files)} files + upload list; {len(insts)} instances; {n} tasks; {k} upload hashes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
