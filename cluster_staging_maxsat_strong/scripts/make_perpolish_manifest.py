#!/usr/bin/env python3
"""Batch PP10: the polish's share of each slot, hard.moves.per_polish {200, 10}, on
24 MSE instances with hard clauses.

docs/current2/PERPOLISH_RUN.md (repo). Workstation only (the login node runs no
Python). Writes, from the tree root:

  configs/strong/perpolish_<arm>.yaml         one config per arm
  scripts/instances_perpolish.csv             the instances
  scripts/manifest_perpolish.tsv / .tasks.csv / .sha256 / .upload.sha256
  scripts/rsync_files_perpolish.txt

    python3 scripts/make_perpolish_manifest.py            # write
    python3 scripts/make_perpolish_manifest.py --check    # regenerate in memory, compare

Instances (NOTES_2026-10-21_AGENDA_AND_STATS.md section 1, user 2026-10-21: "add
the instance you want"):
  - the 16 KS2 instances (scripts/instances_ks2check.csv; proven optima);
  - the 3 setcover rail instances (lean tables; MSE 2024 best-knowns);
  - 5 from the weak HMSE families (scripts/instances_hardmse.csv h003, h047,
    h011, h100, h095; best-knowns), each the instance whose median-run gap is
    closest to its family's median.
Every instance has hard clauses, so auto_hparams/2 R4 (pop 10, keep_sat ks2) is
on in both arms; the arms differ only in hard.moves.per_polish (200 = today's
default). Rail motivation: LONG_CLAUSE_RULE_DESIGN.md section 9.
24 instances x 2 arms x seeds 1-3 = 144 tasks, 900 s, stop at the target.
"""
from __future__ import annotations

import argparse
import copy
import csv
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

import make_hardmse_manifest as hm  # noqa: E402  (family)
import make_oracle900_manifest as o9  # noqa: E402  (sha256, upload helpers)
import make_under30_manifest as u3  # noqa: E402  (sidecar_csv, write_upload, check_or_write)
from evo.auto_hparams import auto_base  # noqa: E402

STEM = "manifest_perpolish"
STAGE = "perpolish"
INSTANCES_CSV = "scripts/instances_perpolish.csv"
SEEDS = (1, 2, 3)
BUDGET = 900
ARMS = {"pp200": 200, "pp10": 10}           # name: hard.moves.per_polish
HMSE_PICKS = ("h003", "h047", "h011", "h100", "h095")
RAIL = ("setcover_wt-rail507.wcnf", "setcover_wt-rail516.wcnf", "setcover_wt-rail582.wcnf")
RAIL_DIR = "data/raw/mse_2024/mse24-small"
INST_COLS = ["pop_idx", "group", "src_idx", "instance", "instance_sha256", "year", "family", "oracle_cost",
             "oracle_kind"]
# pop_size is the config's value; R4 sets 10 at run time (the record's `hparams` field), as in HMSE.
SIDECAR = ["task_id", "job_id", "stage", "arm", "config_id", "config", "per_polish", "pop_size", "ls_time_limit_s",
           "deadline_mode", "solver_seed", "budget_s", "pop_idx", "group", "src_idx", "instance", "instance_sha256",
           "year", "family", "oracle_cost", "oracle_kind", "memetic_impl", "ls_polish_flips", "ls_polish_cap",
           "preprocess", "ls_native"]


def config_path(arm: str) -> str:
    return f"configs/strong/perpolish_{arm}.yaml"


def config_text(arm: str) -> str:
    cfg = copy.deepcopy(auto_base())
    cfg["hard"] = {"moves": {"per_polish": ARMS[arm]}}
    head = (f"# Batch PP10, arm `{arm}`: hard.moves.per_polish {ARMS[arm]}.\n"
            "# Generated by scripts/make_perpolish_manifest.py -- do not edit by hand.\n"
            "# Base: configs/strong/auto.yaml (auto_hparams.auto_base); R4 still sets pop 10 and keep_sat ks2\n"
            "# on hard instances (deep merge keeps per_polish). docs/current2/PERPOLISH_RUN.md (repo).\n")
    return head + yaml.safe_dump(cfg, sort_keys=False)


def bestknown_mse24(staging: str) -> dict:
    with open(os.path.join(staging, "data/raw/mse_2024/bestknown_mse24.csv"), encoding="utf-8") as f:
        return {r["instance"]: int(r["best_cost"]) for r in csv.DictReader(f)}


def select(staging: str):
    """KS2 16, rail 3, HMSE 5, in that order; the instance files must already be in this tree."""
    rows = []
    with open(os.path.join(ROOT, "scripts/instances_ks2check.csv"), encoding="utf-8") as f:
        for r in csv.DictReader(f):
            rows.append({"group": "ks2", "src_idx": r["pop_idx"], "instance": r["instance"],
                         "instance_sha256": r["instance_sha256"], "year": r["year"],
                         "oracle_cost": int(r["oracle_cost"]), "oracle_kind": "proven"})
    best = bestknown_mse24(staging)
    for fname in RAIL:
        inst = f"{RAIL_DIR}/{fname}"
        rows.append({"group": "rail", "src_idx": fname.split("-")[-1].split(".")[0], "instance": inst,
                     "instance_sha256": o9.sha256(os.path.join(ROOT, inst)), "year": "mse24",
                     "oracle_cost": best[fname], "oracle_kind": "best_known"})
    with open(os.path.join(ROOT, hm.INSTANCES_CSV), encoding="utf-8") as f:
        hmse = {r["pop_idx"]: r for r in csv.DictReader(f)}
    for idx in HMSE_PICKS:
        r = hmse[idx]
        rows.append({"group": "hmse", "src_idx": idx, "instance": r["instance"],
                     "instance_sha256": r["instance_sha256"], "year": r["year"],
                     "oracle_cost": int(r["oracle_cost"]), "oracle_kind": r["oracle_kind"]})
    seen = set()
    for i, r in enumerate(rows, 1):
        if r["instance"] in seen:
            raise SystemExit(f"FATAL: {r['instance']} selected twice")
        seen.add(r["instance"])
        if o9.sha256(os.path.join(ROOT, r["instance"])) != r["instance_sha256"]:
            raise SystemExit(f"FATAL: {r['instance']} does not match its recorded sha256")
        r["pop_idx"] = f"p{i:02d}"
        r["family"] = hm.family(os.path.basename(r["instance"]))
    return rows


def instances_csv(rows) -> str:
    return u3.sidecar_csv(INST_COLS, rows)


def build(insts):
    files = {config_path(a): config_text(a) for a in ARMS}
    files[INSTANCES_CSV] = instances_csv(insts)
    out, lines = [], []
    for arm, pp in ARMS.items():
        cid = f"perpolish_{arm}"
        for inst in insts:
            tier, run = ("evalmaxsat", "evalmaxsat_mse_s1") if inst["oracle_kind"] == "proven" else (
                "bestknown", f"bestknown_{inst['year']}")
            for seed in SEEDS:
                job = f"pp_{arm}_{inst['pop_idx']}_s{seed}"
                out.append({
                    "task_id": len(out) + 1, "job_id": job, "stage": STAGE, "arm": arm, "config_id": cid,
                    "config": config_path(arm), "per_polish": pp, "pop_size": 40, "ls_time_limit_s": 3.5,
                    "deadline_mode": "clip", "solver_seed": seed, "budget_s": BUDGET,
                    "pop_idx": inst["pop_idx"], "group": inst["group"], "src_idx": inst["src_idx"],
                    "instance": inst["instance"], "instance_sha256": inst["instance_sha256"],
                    "year": inst["year"], "family": inst["family"], "oracle_cost": inst["oracle_cost"],
                    "oracle_kind": inst["oracle_kind"], "memetic_impl": "v3", "ls_polish_flips": 12500,
                    "ls_polish_cap": "flips", "preprocess": "kernel", "ls_native": "1",
                })
                lines.append("\t".join([job, inst["instance"], config_path(arm), cid, str(seed), str(BUDGET),
                                        str(inst["oracle_cost"]), tier, run]) + "\n")
    files[f"scripts/{STEM}.tsv"] = "".join(lines)
    files[f"scripts/{STEM}.tasks.csv"] = u3.sidecar_csv(SIDECAR, out)
    files[f"scripts/{STEM}.sha256"] = "".join(f"{i['instance_sha256']}  {i['instance']}\n" for i in insts)
    return files


def upload_paths(insts):
    src, _, scripts, _ = o9.upload_paths([])
    scripts = [p for p in scripts if "oracle900" not in p] + [
        "scripts/make_oracle900_manifest.py", "scripts/make_under30_manifest.py", "scripts/make_hardmse_manifest.py",
        "scripts/make_ks2check_manifest.py", "scripts/make_perpolish_manifest.py", "scripts/make_flat_upload.py",
        INSTANCES_CSV, f"scripts/{STEM}.tsv", f"scripts/{STEM}.tasks.csv", f"scripts/{STEM}.sha256"]
    return src, [config_path(a) for a in ARMS], scripts, [i["instance"] for i in insts]


def file_list_text(groups, n_tasks):
    src, cfgs, scripts, data = groups
    out = [f"# File list for batch PP10 ({n_tasks} tasks; docs/current2/PERPOLISH_RUN.md, repo).",
           "# Paths relative to cluster_staging_maxsat_strong/. Destination: ~/cluster_staging_maxsat_strong/.",
           f"# After the upload: sha256sum -c scripts/{STEM}.upload.sha256 on the login node.",
           "#", "# 1. code (src/, including the C core source: REBUILD it with scripts/build_native.sbatch,",
           "#    the lean tables changed ls_core.c)"]
    out += src + ["# 2. configs (one per arm)"] + cfgs
    out += ["# 3. driver, submit, build, results, manifest"] + scripts
    out += [f"scripts/{STEM}.upload.sha256", f"scripts/rsync_files_{STAGE}.txt"]
    out += [f"# 4. instances ({len(data)})"] + data
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--staging", default=o9.STAGING, help="tree holding bestknown_mse24.csv")
    ap.add_argument("--check", action="store_true", help="regenerate the manifest files in memory and compare")
    a = ap.parse_args(argv)
    insts = select(a.staging)
    files = build(insts)
    if a.check:
        return u3.check_or_write(files, True)
    u3.check_or_write(files, False)
    n = files[f"scripts/{STEM}.tsv"].count("\n")
    groups = upload_paths(insts)
    k = u3.write_upload(STEM, STAGE, groups, file_list_text(groups, n))
    print(f"wrote {len(files)} files + upload list; {len(insts)} instances; {n} tasks; {k} upload hashes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
