#!/usr/bin/env python3
"""Stronger-memetic batch S1: leave-one-out on calib_2sat_sc2, raw and kernel.

docs/current2/STRONGER_MEMETIC_DESIGN.md §8.3 (repo). Workstation only (the
login node runs no Python). Writes, from the tree root:

  configs/strong/<arm>_<raw|kern>.yaml        one config per arm and variant
  scripts/manifest_strong_s1.tsv              driver lines (tier2_memetic_array.sbatch)
  scripts/manifest_strong_s1.tasks.csv        sidecar (scripts/m2_results.py)
  scripts/manifest_strong_s1.sha256           the instances
  scripts/manifest_strong_s1.upload.sha256    every file the cluster needs (sha256sum -c)
  scripts/rsync_files_strong_s1.txt           rsync --files-from list

    python3 scripts/make_strong_manifest.py            # write
    python3 scripts/make_strong_manifest.py --check    # regenerate in memory, compare

Arms (all impl v3; values pre-registered for this batch only, design §8.3):
  base    nothing new (= v2 on these soft-only instances)
  all     B1 cc + B2 dls + B3 walk k16 + B4 px
  noB1 .. noB4   all minus one component
  B3only  walk k16 only            (§6.1: B2's effect on raw needs B3)
  wccB3   walksat+cc + walk k16    (§6.2: B1 in the WalkSAT core)
  allC    all with the C core (B5; compared with `all` only)
6 instances x seeds 1-3 x 9 arms x {raw, kern} = 324 tasks, 900 s, stop at c*.
"""
from __future__ import annotations

import argparse
import csv
import glob
import hashlib
import io
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STEM = "manifest_strong_s1"
STAGE = "strong_s1"
SEEDS = (1, 2, 3)
BUDGET = 900

BASE = {  # memetic_deeppolish_p40_ls3p5_v2.yaml, impl v2 -> v3, every other key unchanged
    "impl": "v3",
    "ea": {"enabled": True, "pop_size": 40, "tournament_k": 3, "pmutate": 0.02, "elitism": True,
           "max_gens": 1000000, "deadline_mode": "clip"},
    "ls": {"ls_polish_flips": 12500, "time_limit_s": 3.5, "flip_budget": 12500},
}
B1 = {"tabu": "cc"}
B2 = {"core": "dls", "dls_t": 15, "dls_sp": 0.01, "dls_zeta": 50, "dls_h_inc": 1, "weights": "call"}
B3 = {"mutation": "walk", "mutation_k": 16}
B4 = {"crossover": "px", "px_min_q": 2, "px_fallback": "clause_aware"}

ARMS = {  # name: (ea extra, ls extra, why)
    "base": ({}, {}, "baseline: v3 with no new component (= v2 here)"),
    "all": ({**B3, **B4}, {**B1, **B2}, "B1 cc + B2 dls + B3 walk + B4 px"),
    "noB1": ({**B3, **B4}, {**B2}, "all minus B1 (dls without cc)"),
    "noB2": ({**B3, **B4}, {**B1}, "all minus B2 (walksat + cc)"),
    "noB3": ({**B4}, {**B1, **B2}, "all minus B3 (fixed-rate mutation)"),
    "noB4": ({**B3}, {**B1, **B2}, "all minus B4 (clause-aware crossover)"),
    "B3only": ({**B3}, {}, "B3 alone (design 6.1)"),
    "wccB3": ({**B3}, {**B1}, "walksat + cc + B3 (design 6.2)"),
    "allC": ({**B3, **B4}, {**B1, **B2, "native": True}, "all with the C core (B5)"),
}
VARIANTS = {
    "raw": {},
    "kern": {"preprocess": "kernel", "preprocess_gate": {"screen_min": 0.2, "gain_min": 0.2}},
}
SIDECAR = ["task_id", "job_id", "stage", "arm", "variant", "config_id", "config", "pop_size",
           "ls_time_limit_s", "deadline_mode", "solver_seed", "budget_s", "pilot_idx", "pop_idx", "instance",
           "instance_sha256", "batch", "cell_id", "gen_seed", "m", "oracle_cost", "rc2_solve_s", "rc2_tier",
           "analysis_group", "memetic_impl", "ls_polish_flips", "ls_polish_cap", "preprocess", "ls_native"]


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def config_text(arm: str, variant: str) -> str:
    ea_x, ls_x, why = ARMS[arm]
    cfg = {"impl": BASE["impl"]}
    cfg.update(VARIANTS[variant])
    cfg["ea"] = {**BASE["ea"], **ea_x}
    cfg["ls"] = {**BASE["ls"], **ls_x}
    head = (f"# Stronger memetic, batch S1, arm `{arm}` ({variant}): {why}.\n"
            f"# Generated by scripts/make_strong_manifest.py -- do not edit by hand.\n"
            f"# Base: memetic_deeppolish_p40_ls3p5_v2.yaml with impl v3 (src/evo/v3.py);\n"
            f"# design: docs/current2/STRONGER_MEMETIC_DESIGN.md §8.3 (repo).\n")
    return head + yaml.safe_dump(cfg, sort_keys=False, default_flow_style=False)


def instances():
    with open(os.path.join(ROOT, "scripts", "instances_calib_2sat_sc2.csv"), encoding="utf-8") as f:
        return list(csv.DictReader(f))


def build():
    files = {}
    for arm in ARMS:
        for variant in VARIANTS:
            files[f"configs/strong/{arm}_{variant}.yaml"] = config_text(arm, variant)
    rows, lines = [], []
    insts = instances()
    for arm in ARMS:
        for variant in VARIANTS:
            for inst in insts:
                for seed in SEEDS:
                    job = f"st_{arm}_{variant[0]}_{inst['pop_idx'][2:]}_s{seed}"
                    config = f"configs/strong/{arm}_{variant}.yaml"
                    cid = f"strong_{arm}_{variant}"
                    rows.append({
                        "task_id": len(rows) + 1, "job_id": job, "stage": STAGE, "arm": arm, "variant": variant,
                        "config_id": cid, "config": config, "pop_size": 40, "ls_time_limit_s": 3.5,
                        "deadline_mode": "clip", "solver_seed": seed, "budget_s": BUDGET, "pilot_idx": "",
                        "pop_idx": inst["pop_idx"], "instance": inst["instance"],
                        "instance_sha256": inst["instance_sha256"], "batch": inst["batch"],
                        "cell_id": inst["cell_id"], "gen_seed": inst["gen_seed"], "m": inst["m"],
                        "oracle_cost": inst["oracle_cost"], "rc2_solve_s": inst["rc2_solve_s"],
                        "rc2_tier": inst["rc2_tier"], "analysis_group": inst["analysis_group"],
                        "memetic_impl": "v3", "ls_polish_flips": 12500, "ls_polish_cap": "flips",
                        "preprocess": "kernel" if variant == "kern" else "",
                        "ls_native": "1" if ARMS[arm][1].get("native") else "0",
                    })
                    lines.append("\t".join([job, inst["instance"], config, cid, str(seed), str(BUDGET),
                                            inst["oracle_cost"], inst["rc2_tier"], inst["batch"]]) + "\n")
    files[f"scripts/{STEM}.tsv"] = "".join(lines)
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=SIDECAR, lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    files[f"scripts/{STEM}.tasks.csv"] = buf.getvalue()
    files[f"scripts/{STEM}.sha256"] = "".join(f"{i['instance_sha256']}  {i['instance']}\n" for i in insts)
    return files, insts


def upload_paths(insts):
    src = sorted(p for p in glob.glob("src/**/*.py", root_dir=ROOT, recursive=True) if "__pycache__" not in p)
    src += ["src/native/ls_core.c"]
    cfgs = sorted(f"configs/strong/{a}_{v}.yaml" for a in ARMS for v in VARIANTS)
    scripts = ["scripts/tier2_memetic_array.sbatch", "scripts/submit_m2_memetic.sh", "scripts/build_native.sh",
               "scripts/build_native.sbatch", "scripts/m2_results.py", "scripts/make_strong_manifest.py",
               "scripts/instances_calib_2sat_sc2.csv", f"scripts/{STEM}.tsv", f"scripts/{STEM}.tasks.csv",
               f"scripts/{STEM}.sha256"]
    data = [i["instance"] for i in insts]
    return src, cfgs, scripts, data


def rsync_text(groups):
    src, cfgs, scripts, data = groups
    out = ["# rsync --files-from list for the stronger-memetic batch S1 (324 tasks;",
           "# docs/current2/STRONGER_MEMETIC_DESIGN.md §8.3, repo). Paths relative to",
           "# cluster_staging_maxsat_strong/. Destination: ~/cluster_staging_maxsat_strong/ (a new tree).",
           f"# After the rsync: sha256sum -c scripts/{STEM}.upload.sha256 on the login node.",
           "#", "# 1. code (src/, including the C core source; build it once with scripts/build_native.sh)"]
    out += src
    out += ["# 2. configs (one per arm and variant)"] + cfgs
    out += ["# 3. driver, submit, build, results, manifest"] + scripts
    out += [f"scripts/{STEM}.upload.sha256", "scripts/rsync_files_strong_s1.txt"]
    out += ["# 4. instances (the six eligible calib_2sat_sc2 instances)"] + data
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    files, insts = build()
    if a.check:
        bad = [p for p, txt in files.items()
               if not os.path.isfile(os.path.join(ROOT, p)) or open(os.path.join(ROOT, p), encoding="utf-8").read() != txt]
        if bad:
            print("DIFFERS:", *bad, sep="\n  ")
            return 1
        print(f"OK: {len(files)} files reproduce byte for byte")
        return 0
    for p, txt in files.items():
        full = os.path.join(ROOT, p)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8", newline="") as f:
            f.write(txt)
    for i in insts:
        if sha256(os.path.join(ROOT, i["instance"])) != i["instance_sha256"]:
            print(f"FATAL: {i['instance']} does not match its recorded sha256", file=sys.stderr)
            return 1
    groups = upload_paths(insts)
    with open(os.path.join(ROOT, "scripts", "rsync_files_strong_s1.txt"), "w", encoding="utf-8") as f:
        f.write(rsync_text(groups))
    every = [p for g in groups for p in g] + ["scripts/rsync_files_strong_s1.txt"]
    with open(os.path.join(ROOT, "scripts", f"{STEM}.upload.sha256"), "w", encoding="utf-8") as f:
        f.writelines(f"{sha256(os.path.join(ROOT, p))}  {p}\n" for p in every)
    n = files[f"scripts/{STEM}.tsv"].count("\n")
    print(f"wrote {len(files)} files + upload list; {n} tasks; {len(every)} upload hashes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
